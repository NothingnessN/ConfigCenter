#!/usr/bin/env python3
"""Import only reachable values from the untouched Android 11 ConfigCenter.

This is resource-source generation, not an Android build. The closure starts at
the retained Java/XML and hand-written values. Hand-written overrides replace
upstream values in every locale; old translations therefore cannot describe a
removed feature. Raw value elements and upstream license headers are preserved.
"""

import argparse
from pathlib import Path
import re
import xml.etree.ElementTree as ET


RENAMED = {
    "disabled",
    "smart_pixels_percent_strings", "smart_pixels_percent_values",
    "smart_pixels_shift_times", "smart_pixels_shift_values",
    "adaptive_playback_timeout_10_min", "adaptive_playback_timeout_1_min",
    "adaptive_playback_timeout_2_min", "adaptive_playback_timeout_30_secs",
    "adaptive_playback_timeout_5_min", "adaptive_playback_timeout_title",
    "default_string", "display_cutout_force_fullscreen_summary",
    "display_cutout_force_fullscreen_title",
    "less_boring_heads_up_summary", "less_boring_heads_up_title",
    "lockscreen_battery_info_summary", "lockscreen_battery_info_title",
    "notification_sound_vib_screen_on_summary",
    "notification_sound_vib_screen_on_title", "notifications_title",
    "smart_pixels_percent", "smart_pixels_summary", "smart_pixels_title",
}

STAMP = "<!-- Generated by tools/import_resources.py; do not edit. -->\n"
VALUE_ELEMENT = re.compile(
    r'^[ \t]*<(?P<tag>string|integer-array|string-array|plurals)\b'
    r'(?P<attrs>[^>]*\bname="(?P<name>[^"]+)"[^>]*)>'
    r'(?P<value>.*?)</(?P=tag)>[ \t]*\n?', re.MULTILINE | re.DOTALL)
XML_REFERENCE = re.compile(r'@(?:\+)?(string|array|plurals)/([\w.]+)')
JAVA_REFERENCE = re.compile(r'(?<![\w.])R\.(string|array|plurals)\.(\w+)')


def references(text):
    return set(XML_REFERENCE.findall(text)) | set(JAVA_REFERENCE.findall(text))


def resource_type(tag):
    return "array" if tag.endswith("-array") else tag


def rebrand_text_nodes(text):
    parts = re.split(r'(<!--.*?-->|<[^>]*>)', text, flags=re.DOTALL)
    for index, part in enumerate(parts):
        if part.startswith('<') or re.search(r'https?:|github|\.com|@|ro\.havoc', part, re.I):
            continue
        part = re.sub(r'(?<![.\w/])(?:Havoc|HAVOC)[- ]?(?i:OS)\b', 'D4RK OS', part)
        parts[index] = re.sub(r'(?<![.\w/])(?:Havoc|HAVOC)', 'D4RK', part)
    return ''.join(parts)


def adapt(text):
    text = rebrand_text_nodes(text)
    for name in sorted(RENAMED, key=len, reverse=True):
        text = re.sub(r'(\bname=")' + re.escape(name) + r'(")',
                      r'\g<1>d4rk_' + name + r'\2', text)
        text = re.sub(r'(@(?:string|array)/)' + re.escape(name) + r'\b',
                      r'\g<1>d4rk_' + name, text)
    return text


def plan(source, bundle, output):
    files = sorted((source / "res").glob("values*/havoc_*.xml"))
    if not files:
        raise ValueError("No upstream value resources found")
    upstream = {}
    default = {}
    for file in files:
        text = adapt(file.read_text())
        ET.fromstring(text)
        entries = [(resource_type(match["tag"]), match["name"], match[0])
                   for match in VALUE_ELEMENT.finditer(text)]
        upstream[file] = (text, entries)
        if file.parent.name == "values":
            for kind, name, value in entries:
                key = (kind, name)
                if key in default:
                    raise ValueError(f"Duplicate upstream default: {key}")
                default[key] = value

    provided = set()
    roots = set()
    for file in sorted((bundle / "src").rglob("*.java")):
        roots |= references(file.read_text())
    for file in sorted((bundle / "res").rglob("*.xml")):
        text = file.read_text()
        if file.parent.name.startswith("values"):
            if file.name.startswith("d4rk_legacy_"):
                if STAMP not in text:
                    raise ValueError(f"Generated output was replaced by a user file: {file}")
                continue
            for element in ET.fromstring(text):
                if element.get("name"):
                    provided.add((resource_type(element.tag), element.get("name")))
        roots |= references(text)

    # Include references from translations too, so a translated array cannot
    # introduce an unresolved reference that the English closure overlooked.
    selected = roots - provided
    while True:
        additions = set()
        for _, entries in upstream.values():
            for kind, name, value in entries:
                if (kind, name) in selected:
                    additions |= references(value) - provided
        expanded = selected | additions
        if expanded == selected:
            break
        selected = expanded
    missing = selected - default.keys()
    if missing:
        raise ValueError(f"No upstream defaults for retained resources: {sorted(missing)}")
    if any(name.startswith("status_bar_logo") for _, name in selected):
        raise ValueError("Excluded status-bar-logo resource is reachable")

    results = {}
    for file, (text, entries) in upstream.items():
        retained = [value.rstrip() for kind, name, value in entries
                    if (kind, name) in selected
                    and (file.parent.name == "values"
                         or 'translatable="false"' not in default[(kind, name)])]
        if not retained:
            continue
        root = re.search(r"<resources\b[^>]*>", text)
        header = text[:root.start()]
        data = header + STAMP + root[0] + "\n\n" + "\n\n".join(retained) + "\n</resources>\n"
        ET.fromstring(data)
        dest = output / file.parent.name / file.name.replace("havoc_", "d4rk_legacy_", 1)
        results[dest] = data
    return results, selected


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", required=True, type=Path,
                        help="Untouched Android 11 ConfigCenter source directory")
    parser.add_argument("--bundle", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--output", type=Path,
                        help="Output res directory (default: the bundle's res)")
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="Verify without writing")
    mode.add_argument("--update", action="store_true",
                      help="Regenerate/prune only files carrying the generator stamp")
    args = parser.parse_args()
    source = args.source.resolve()
    bundle = args.bundle.resolve()
    output = (args.output or bundle / "res").resolve()
    if source == output or source in output.parents or output in source.parents:
        parser.error("Source and output must be separate trees")
    try:
        results, selected = plan(source, bundle, output)
        existing = set(output.glob("values*/d4rk_legacy_*.xml"))
        stale = existing - results.keys()
        changed = {dest for dest, data in results.items()
                   if not dest.exists() or dest.read_text() != data}
        for dest in existing:
            if STAMP not in dest.read_text():
                raise ValueError(f"Refusing to touch an unmarked file: {dest}")
        if args.check and (stale or changed):
            raise ValueError(f"Generated resources differ: {sorted(stale | changed)}")
        if not args.check:
            if not args.update and (stale or any(dest.exists() for dest in changed)):
                raise ValueError("Outputs differ; review them and use --update to regenerate")
            for dest in sorted(stale):
                dest.unlink()
                if not any(dest.parent.iterdir()):
                    dest.parent.rmdir()
            for dest in sorted(changed):
                dest.parent.mkdir(parents=True, exist_ok=True)
                dest.write_text(results[dest])
        print(f"Verified {len(selected)} reachable values in {len(results)} generated files"
              if args.check else
              f"Generated {len(selected)} reachable values in {len(results)} files;"
              f" removed {len(stale)} obsolete generated files")
    except (ValueError, ET.ParseError) as error:
        parser.error(str(error))


if __name__ == "__main__":
    main()
